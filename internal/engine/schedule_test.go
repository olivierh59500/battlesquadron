// The fingerprints are generated by the original 68000 direction handler,
// stopping before graphics. No second native movement decoder supplies them.
func TestDirectedFormationsAgainstOriginal68000(t *testing.T) {
	loader, err := os.ReadFile("../../assets/unpacked/loader.bin")
	if os.IsNotExist(err) {
		t.Skip("extract the original ADF to compare flight trajectories")
	}
	if err != nil {
		t.Fatal(err)
	}
	overlays := map[string][]byte{}
	for _, name := range []string{"lods0f", "lodst1", "lodst2", "lodst3"} {
		overlays[name], err = os.ReadFile("../../assets/unpacked/" + name + ".bin")
		if err != nil {
			t.Fatal(err)
		}
	}
	schedules, err := NativeSchedules(loader, 0x100, overlays)
	if err != nil {
		t.Fatal(err)
	}
	encoded, err := os.ReadFile("wave_oracle_test.json")
	if err != nil {
		t.Fatal(err)
	}
	var references []struct {
		Stage, Event, Ticks int
		Hash                string
	}
	if err = json.Unmarshal(encoded, &references); err != nil {
		t.Fatal(err)
	}
	if len(references) != 56 {
		t.Fatalf("original directed formation count=%d;expected56", len(references))
	}
	for _, r := range references {
		event := schedules[r.Stage][r.Event]
		x, y := int32(288<<16), int32(20<<16)
		trajectory := []byte{}
		index, remaining := 0, 0
		var motion Motion
		for tick := 0; tick < r.Ticks; tick++ {
			if remaining == 0 {
				if index == len(event.Script) {
					if !event.RepeatScript {
						t.Fatalf("stage%d event%d native script ended at tick%d,originalruns%d", r.Stage, r.Event, tick, r.Ticks)
					}
					index = event.ScriptLoop
				}
				motion = event.Script[index]
				index++
				remaining = motion.Duration
			}
			x += int32(motion.VX)
			y += int32(motion.VY)
			remaining--
			frame := make([]byte, 9)
			binary.BigEndian.PutUint32(frame, uint32(x))
			binary.BigEndian.PutUint32(frame[4:], uint32(y))
			frame[8] = byte(motion.Frame)
			trajectory = append(trajectory, frame...)
		}
		hash := fmt.Sprintf("%x", sha256.Sum256(trajectory))
		if hash != r.Hash {
			t.Fatalf("stage%d event%d native trajectory=%s;original=%s", r.Stage, r.Event, hash, r.Hash)
		}
	}
}
