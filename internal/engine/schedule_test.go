func TestOriginalFlyingSchedules(t *testing.T) {
	loader, err := os.ReadFile("../../assets/unpacked/loader.bin")
	if os.IsNotExist(err) {
		t.Skip("extract the original ADF to verify its flying schedules")
	}
	if err != nil {
		t.Fatal(err)
	}
	overlays := map[string][]byte{}
	for _, name := range []string{"lods0f", "lodst1", "lodst2", "lodst3"} {
		overlays[name], err = os.ReadFile("../../assets/unpacked/" + name + ".bin")
		if err != nil {
			t.Fatal(err)
		}
	}
	schedules, err := NativeSchedules(loader, 0x100, overlays)
	if err != nil {
		t.Fatal(err)
	}
	for stage, count := range []int{169, 139, 161, 205} {
		if len(schedules[stage]) != count {
			t.Fatalf("stage%d has%d records; expected%d original records", stage, len(schedules[stage]), count)
		}
	}
	first := schedules[0][0]
	if first.Progress != 330 || first.X != 0 || first.Y != -32 || first.RandomMode != 1 || first.Definition.NativeKind != 1 || first.Definition.Width != 32 || first.Definition.Height != 32 {
		t.Fatalf("first original wave=%+v", first)
	}
	formation := schedules[0][3]
	if first.Definition.Score != 5000 {
		t.Fatalf("original packed decimal ship score=%d", first.Definition.Score)
	}
	if formation.Progress != 500 || formation.X != 288 || formation.Y != 20 || len(formation.Script) == 0 {
		t.Fatalf("first directed formation=%+v", formation)
	}
	motion := formation.Script[0]
	if motion.Duration != 40 || motion.VX != -4<<16 || motion.VY != 0 || motion.Frame != 12 {
		t.Fatalf("original formation first motion=%+v", motion)
	}
	if formation.RepeatScript {
		t.Fatal("the first original formation terminates with FF01")
	}
	scripted := 0
	for _, stage := range schedules {
		for _, event := range stage {
			if len(event.Script) != 0 {
				scripted++
			}
		}
	}
	if scripted < 100 {
		t.Fatalf("only%d original scripted formations were recovered", scripted)
	}
}

